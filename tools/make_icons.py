#!/usr/bin/env python3
"""Writes src/plugin/MeowIcons.h from the icon table of the approved mockup (docs/mockups/app.js)."""
import re, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(root, 'docs/mockups/app.js')).read()
i = s.index('const IC = {'); j = s.index('};', i)
items = re.findall(r"(\w+):\s*'((?:[^'\\]|\\.)*)'", s[i + len('const IC = {'):j])
out = ['#pragma once', '#include <string>', '// Icons from the approved mockup (docs/mockups/app.js), 20 by 20 grid, stroke only. Generated by tools/make_icons.py.',
       'namespace mcicons {', 'struct Def { const char* name; const char* inner; };', 'inline const Def kIcons[] = {']
out += ['    { "%s", R"SVG(%s)SVG" },' % (k, v) for k, v in items]
out += ['};', 'inline const char* find(const std::string& n) { for (auto& d : kIcons) if (n == d.name) return d.inner; return ""; }', '}', '']
open(os.path.join(root, 'src/plugin/MeowIcons.h'), 'w').write('\n'.join(out))
print(len(items), 'icons')
